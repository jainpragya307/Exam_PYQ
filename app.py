import re
from pathlib import Path

import matplotlib.pyplot as plt
import pandas as pd
import streamlit as st
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.metrics.pairwise import cosine_similarity

st.set_page_config(page_title="Exam Prep & PYQ Assistant", page_icon="📚", layout="wide")

DATA_DIR = Path(__file__).parent / "data"

@st.cache_data
def load_data():
    students = pd.read_csv(DATA_DIR / "students.csv")
    subjects = pd.read_csv(DATA_DIR / "subjects.csv")
    questions = pd.read_csv(DATA_DIR / "questions.csv")
    return students, subjects, questions

students, subjects, questions = load_data()
subject_names = dict(zip(subjects["subject_id"], subjects["subject_name"]))

st.title("📚 Exam Preparation & PYQ Assistant")
st.caption("Subject-wise previous-year questions, stored answers, and smart text retrieval")

with st.sidebar:
    st.header("Student")
    selected_student = st.selectbox(
        "Choose student",
        students["student_id"],
        format_func=lambda sid: f"{students.loc[students.student_id == sid, 'name'].iloc[0]} ({sid})"
    )
    student = students.loc[students["student_id"] == selected_student].iloc[0]
    st.write(f"**Semester:** {student['semester']}")
    st.write(f"**Department:** {student['department']}")
    st.divider()
    page = st.radio("Navigate", ["Question Bank", "Smart Answer Finder", "Data Insights"])

if page == "Question Bank":
    st.header("Subject-wise Question Bank")
    subject_id = st.selectbox(
        "Select subject",
        subjects["subject_id"],
        format_func=lambda sid: subject_names[sid]
    )
    filtered = questions[questions["subject_id"] == subject_id].copy()
    units = sorted(filtered["unit"].unique().tolist())
    unit_choice = st.selectbox("Select unit", ["All units"] + [f"Unit {u}" for u in units])
    if unit_choice != "All units":
        filtered = filtered[filtered["unit"] == int(unit_choice.split()[1])]
    st.write(f"**Questions found:** {len(filtered)}")
    for _, row in filtered.sort_values(["unit", "year"], ascending=[True, False]).iterrows():
        with st.expander(f"{row['question']}  |  {row['marks']} marks  |  {row['year']}"):
            st.write(f"**Unit:** {row['unit']}  •  **Question ID:** {row['question_id']}")
            st.write("**Suggested answer**")
            st.write(row["answer"])
            st.caption(f"Keywords: {row['keywords']}")

elif page == "Smart Answer Finder":
    st.header("Smart Answer Finder")
    st.write("Ask in your own words. The app searches the selected subject's stored questions and answers.")
    subject_id = st.selectbox(
        "Search within subject",
        subjects["subject_id"],
        format_func=lambda sid: subject_names[sid],
        key="search_subject"
    )
    user_query = st.text_input("Enter your question", placeholder="e.g. How are TCP and UDP different?")
    threshold = st.slider("Minimum similarity to accept a match", 0.05, 0.60, 0.15, 0.05)
    if st.button("Find Answer", type="primary"):
        if not user_query.strip():
            st.warning("Please enter a question first.")
        else:
            pool = questions[questions["subject_id"] == subject_id].copy().reset_index(drop=True)
            corpus = pool["question"].fillna("").tolist() + pool["keywords"].fillna("").tolist()
            vectorizer = TfidfVectorizer(stop_words="english", ngram_range=(1, 2))
            matrix = vectorizer.fit_transform(corpus + [user_query])
            query_vec = matrix[-1]
            doc_matrix = matrix[:len(corpus)]
            scores = cosine_similarity(query_vec, doc_matrix).flatten()
            n = len(pool)
            question_scores = scores[:n]
            keyword_scores = scores[n:]
            combined = question_scores + 0.35 * keyword_scores
            best_idx = int(combined.argmax())
            best_score = float(combined[best_idx])
            if best_score < threshold:
                st.error("No sufficiently similar question was found. Try different keywords or browse the Question Bank.")
                st.caption(f"Best similarity score: {best_score:.2f}")
            else:
                match = pool.iloc[best_idx]
                st.success(f"Best match found — similarity score: {best_score:.2f}")
                st.subheader(match["question"])
                st.write(match["answer"])
                st.caption(f"Source: {subject_names[subject_id]} • Unit {match['unit']} • {match['year']} • {match['marks']} marks • ID {match['question_id']}")
                st.info("This answer was retrieved from the CSV dataset; it was not newly generated by an AI model.")

elif page == "Data Insights":
    st.header("Question Bank Data Insights")
    c1, c2, c3 = st.columns(3)
    c1.metric("Students", len(students))
    c2.metric("Subjects", len(subjects))
    c3.metric("Questions", len(questions))
    counts = questions.groupby("subject_id").size().rename(index=subject_names)
    st.subheader("Questions per subject")
    st.bar_chart(counts)
    unit_counts = questions.groupby(["subject_id", "unit"]).size().reset_index(name="question_count")
    unit_counts["Subject"] = unit_counts["subject_id"].map(subject_names)
    st.subheader("Question distribution by subject and unit")
    st.dataframe(unit_counts[["Subject", "unit", "question_count"]], use_container_width=True, hide_index=True)
    st.subheader("Question dataset")
    display_df = questions.copy()
    display_df["subject_name"] = display_df["subject_id"].map(subject_names)
    st.dataframe(display_df[["question_id", "subject_name", "unit", "year", "marks", "question"]], use_container_width=True, hide_index=True)
    st.download_button(
        "Download question dataset CSV",
        data=questions.to_csv(index=False).encode("utf-8"),
        file_name="questions_dataset.csv",
        mime="text/csv"
    )

st.divider()
st.caption("Mini-project demo dataset. Replace sample entries with your own verified subject questions and PYQs before submission.")
